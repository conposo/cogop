// Function to process a single church
async function processChurch(churchData) {
  console.log(`📍 Processing church: ${churchData.name}`);
  
  // Create church document matching the existing schema
  const churchDocument = {
    name: churchData.name,
    address: `${churchData.city}, ${churchData.state}`,
    city: churchData.city,
    state: churchData.state,
    zipCode: '',
    country: churchData.country,
    phone: '',
    email: '',
    website: '',
    pastor: '',
    denomination: 'Church of God of Prophecy',
    description: churchData.description,
    servicesTimes: [
      { day: 'Неделя', time: '10:00' }
    ],
    programs: [],
    coordinates: { lat: 0, lng: 0 },
    isActive: true,
    createdAt: Timestamp.fromDate(new Date()),
    createdBy: 'import-script',
    updatedAt: Timestamp.fromDate(new Date()),
    updatedBy: 'import-script'
  };

  return churchDocument;
}

// Main import function
async function importBulgarianChurches() {
  console.log('🚀 Starting Bulgarian churches import...');
  console.log('📝 Skipping image uploads - importing church data only');
  
  let successCount = 0;
  let errorCount = 0;
  const errors = [];

  for (const churchData of bulgarianChurches) {
    try {
      const churchDocument = await processChurch(churchData);
      
      if (churchDocument) {
        // Add to Firestore
        const docRef = await addDoc(collection(db, 'churches'), churchDocument);
        console.log(`✅ Successfully added church: ${churchData.name} (ID: ${docRef.id})`);
        successCount++;
      } else {
        throw new Error('Failed to process church data');
      }
      
    } catch (error) {
      console.error(`❌ Error processing church ${churchData.name}:`, error.message);
      errors.push(`${churchData.name}: ${error.message}`);
      errorCount++;
    }
  }

  // Summary
  console.log('\n📊 Import Summary:');
  console.log(`✅ Successfully imported: ${successCount} churches`);
  console.log(`❌ Errors: ${errorCount} churches`);
  
  if (errors.length > 0) {
    console.log('\n❌ Error details:');
    errors.forEach(error => console.log(`  - ${error}`));
  }
  
  console.log('\n🎉 Import completed!');
}

// Run the import
if (require.main === module) {
  importBulgarianChurches().catch(error => {
    console.error('💥 Fatal error during import:', error);
    process.exit(1);
  });
}

module.exports = { importBulgarianChurches }; 